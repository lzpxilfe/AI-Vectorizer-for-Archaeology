def render_word_mask(text, *, scale, angle, tracking=1, stroke=1):
    """Render only declared atlas glyphs; never substitute missing-font boxes."""
    import numpy as np
    from PIL import Image, ImageDraw

    if (not isinstance(text, str) or not 1 <= len(text) <= 8
            or any(character not in LATIN and character not in CJK for character in text)):
        raise ValueError("synthetic words must use the declared stroke atlas")
    if scale not in (1, 2, 3) or tracking not in (1, 2, 3) or stroke not in (1, 2):
        raise ValueError("synthetic glyph geometry is bounded")
    glyphs = []
    for character in text:
        if character in LATIN:
            rows = LATIN[character]
            glyph = Image.fromarray(np.asarray([[255 if bit == "1" else 0 for bit in row] for row in rows], dtype=np.uint8))
        else:
            glyph = Image.new("L", (9, 9), 0)
            draw = ImageDraw.Draw(glyph)
            for points in CJK[character]:
                draw.line(points, fill=255, width=stroke)
        glyphs.append(glyph.resize((glyph.width * scale, glyph.height * scale), Image.Resampling.NEAREST))
    width = sum(glyph.width for glyph in glyphs) + tracking * scale * (len(glyphs) - 1)
    height = max(glyph.height for glyph in glyphs)
    canvas = Image.new("L", (width + 4, height + 4), 0)
    x = 2
    for glyph in glyphs:
        canvas.paste(glyph, (x, 2 + height - glyph.height))
        x += glyph.width + tracking * scale
    rotated = canvas.rotate(float(angle), resample=Image.Resampling.BILINEAR, expand=True)
    return np.asarray(rotated, dtype=np.float32) / 255.0
